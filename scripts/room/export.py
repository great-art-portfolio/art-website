"""Turns a room render into the site's room assets.

python3 -I scripts/room/export.py <render dir>

Reads <render dir>/room.jpg and room.json (from room.py) and writes:
- public/rooms/living-room-{1000,1600,2000}.webp, the room itself;
- public/rooms/living-room-light.webp, the wall's light (rendered wall over
  its paint colour, blurred), which the page multiplies over the painting
  so the window's falloff lands on it too;
- src/lib/room-data.ts, the room's measurements for src/lib/room.ts.
"""
import json
import os
import sys

from PIL import Image, ImageFilter

# The wall's paint in room.py ("E4DDD1"), in the render's sRGB.
WALL_PAINT = (0xE4, 0xDD, 0xD1)
LIGHT_WIDTH = 500

render = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
room = Image.open(os.path.join(render, "room.jpg")).convert("RGB")
meta = json.load(open(os.path.join(render, "room.json")))

out = os.path.join(root, "public", "rooms")
os.makedirs(out, exist_ok=True)
for w in (1000, 1600, 2000):
    im = room.resize((w, round(room.height * w / room.width)), Image.LANCZOS)
    im.save(os.path.join(out, f"living-room-{w}.webp"), quality=82, method=6)

small = room.resize(
    (LIGHT_WIDTH, round(room.height * LIGHT_WIDTH / room.width)), Image.LANCZOS
)
small = small.filter(ImageFilter.GaussianBlur(6))
light = Image.merge(
    "RGB",
    [
        ch.point(lambda v, p=p: min(255, round(v * 255 / p)))
        for ch, p in zip(small.split(), WALL_PAINT)
    ],
)
light.save(os.path.join(out, "living-room-light.webp"), quality=85, method=6)

ts = f"""// Generated by scripts/room/export.py from the room render. Don't edit.
/** The living-room render: its pixel size, the wall's scale, and where the
 * wall point x = 0 (centre of the sofa), z = 0 (floor) lands. */
export const ROOM = {{
  width: {meta["width"]},
  height: {meta["height"]},
  pxPerMeter: {abs(meta["pxPerMeter"]):.3f},
  wallOriginX: {meta["wallOrigin"][0]:.2f},
  wallOriginY: {meta["wallOrigin"][1]:.2f},
  sofaTopM: {meta["sofaTopM"]:.4f},
  sofaWidthM: {meta["sofaWidthM"]:.4f},
}} as const;
"""
open(os.path.join(root, "src", "lib", "room-data.ts"), "w").write(ts)
print("wrote", out, "and src/lib/room-data.ts")
